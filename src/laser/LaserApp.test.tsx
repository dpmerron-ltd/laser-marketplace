it('edits only the selected material profile and keeps all four materials available', async () => {
  const { emptyWorkspace, parseWorkspace } = await import('./workspace')
  const workspace = emptyWorkspace()
  workspace.materials = workspace.materials.map(m => ({ ...m, approved: true }))
  localStorage.setItem('laser-marketplace-workspace-v1', JSON.stringify(workspace))
  render(<LaserApp />)
  fireEvent.click(screen.getByRole('button', { name: 'Machine & material' }))
  for (const name of ['Plywood · 3 mm', 'Plywood · 6 mm', 'MDF · 3 mm', 'MDF · 6 mm']) expect(screen.getByRole('button', { name: new RegExp('^' + name) })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: /^MDF · 6 mm/ }))
  fireEvent.change(screen.getByRole('spinbutton', { name: 'Measured kerf (mm)' }), { target: { value: '.21' } })
  await waitFor(() => {
    const saved = parseWorkspace(JSON.parse(localStorage.getItem('laser-marketplace-workspace-v1')!))
    expect(saved.materials.find(m => m.id === 'mdf-6mm')!.kerf).toBe(.21)
    expect(saved.materials.find(m => m.id === 'mdf-6mm')!.approved).toBe(false)
    expect(saved.materials.filter(m => m.id !== 'mdf-6mm').every(m => m.approved)).toBe(true)
  })
  fireEvent.change(screen.getByRole('spinbutton', { name: 'Bed width (mm)' }), { target: { value: '800' } })
  await waitFor(() => expect(parseWorkspace(JSON.parse(localStorage.getItem('laser-marketplace-workspace-v1')!)).materials.every(m => !m.approved)).toBe(true))
})

it('prepares separate material batches for matching SKU assignments', async () => {
  const { emptyWorkspace } = await import('./workspace')
  const { demoDesign } = await import('./model')
  const workspace = emptyWorkspace()
  workspace.materials = workspace.materials.map(m => ({ ...m, approved: true }))
  workspace.designs = [{ ...demoDesign, id: 'ply', sku: 'PLY3', materialId: 'plywood-3mm', approved: true }, { ...demoDesign, id: 'mdf', sku: 'MDF6', materialId: 'mdf-6mm', approved: true }]
  localStorage.setItem('laser-marketplace-workspace-v1', JSON.stringify(workspace))
  render(<LaserApp />)
  fireEvent.click(screen.getByRole('button', { name: 'Prepare a batch' }))
  fireEvent.change(screen.getByRole('spinbutton', { name: 'Quantity of PLY3' }), { target: { value: '2' } })
  fireEvent.change(screen.getByRole('spinbutton', { name: 'Quantity of MDF6' }), { target: { value: '3' } })
  fireEvent.click(screen.getByRole('button', { name: 'Prepare batch' }))
  await screen.findByRole('combobox', { name: 'Material batch' })
  expect(screen.getByRole('button', { name: 'Save 2 material batches to queue' })).toBeInTheDocument()
  fireEvent.change(screen.getByRole('combobox', { name: 'Material batch' }), { target: { value: 'mdf-6mm' } })
  expect(screen.getByText(/MDF · 6 mm · 1 sheets · 3 components/)).toBeInTheDocument()
})
